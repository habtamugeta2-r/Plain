//! JavaScript generation.
//!
//! Plain compiles to a small ES module that builds DOM nodes directly. There is
//! no virtual DOM and no diffing: every value that can change is handed to the
//! runtime as an accessor, and the runtime puts exactly one effect around each
//! one, so a change touches the node it belongs to and nothing else.
//!
//! ```text
//! heading "~(count) items"      const n1 = P.el('h1', '');
//!   on click => count = 0       P.setText(n1, () => `${P.text(count())} items`);
//!                               P.on(n1, 'click', (event) => {
//!                                 count.set(0);
//!                               });
//! ```
//!
//! The shape is deliberate. A component is a plain function; its props arrive as
//! accessors and are read with [`P.prop`](crate::expr), so a component re-renders
//! when its parent's state changes without either of them knowing how. Children
//! are built eagerly in the parent's scope and handed down, which is what makes
//! `if` and `each` the only places that need to create a scope of their own.
//!
//! Nothing here invents behaviour. Where an element cannot work without it — a
//! `check` needs `type="checkbox"`, a `toggle` needs to respond to a click — the
//! element's own meaning supplies it, and it is listed in [`implied`] rather than
//! scattered through the generator.

use std::collections::HashMap;

use plain_core::{Diagnostic, FileId};

use crate::ast::{
    Assign, AttrProp, Component, Derive, Each, Element, Expr, FnDecl, Handler, If, Let, Node,
    Program, PropDecl, Return, Slot, StyleProp, Use,
};
use crate::css;
use crate::expr::{self, Binding, Scope};
use crate::tables::{self, ArgRole, Layout};

/// Emits the ES module for one program.
///
/// Call [`module`]; the emitter itself is an implementation detail.
pub struct Emitter {
    file: FileId,
    lines: Vec<String>,
    indent: usize,
    /// Node variables are numbered in creation order, so the same program always
    /// produces the same module.
    nodes: usize,
    /// Each component's declared prop names, in order, so a positional argument
    /// arrives under the name the component reads.
    components: HashMap<String, Vec<String>>,
    /// The first `main` in a program is where the skip link goes, and only the
    /// first: two elements with the same id would make the link guess.
    main_id: bool,
    diagnostics: Vec<Diagnostic>,
}

/// Emits the module for a program whose styles have already been collected by
/// [`css::collect`](crate::css::collect), which is what writes the class onto each
/// element.
///
/// `mount` is the selector the entry point renders into.
pub fn module(program: &Program, mount: &str) -> (String, Vec<Diagnostic>) {
    let components = program
        .components
        .iter()
        .map(|component| {
            (
                component.name.clone(),
                component.props.iter().map(|p| p.name.clone()).collect(),
            )
        })
        .collect();

    let mut emitter = Emitter {
        file: program.file,
        lines: Vec::new(),
        indent: 0,
        nodes: 0,
        components,
        main_id: false,
        diagnostics: Vec::new(),
    };

    emitter.line("/* Generated by Plain. Do not edit by hand. */");
    emitter.line("import { P } from './plain.runtime.js';");

    for component in &program.components {
        emitter.blank();
        emitter.component(component);
    }

    emitter.blank();
    emitter.open("function App() {");
    let mut scope = Scope::new();
    emitter.declare(&program.body, &mut scope);
    let root = emitter.render(&program.body, &mut scope);
    emitter.line(&format!("return {root};"));
    emitter.close("}");

    emitter.blank();
    emitter.line(&format!("P.mount({}, App);", expr::js_string(mount)));

    let diagnostics = std::mem::take(&mut emitter.diagnostics);
    (emitter.lines.join("\n") + "\n", diagnostics)
}

impl Emitter {
    /// Adds a line. `text` may itself span lines — a factory composed into a
    /// call does — and every one of them carries the current indent.
    fn line(&mut self, text: &str) {
        let pad = "  ".repeat(self.indent);
        for (index, part) in text.split('\n').enumerate() {
            let mut out = String::new();
            if index > 0 || !part.is_empty() {
                out.push_str(&pad);
            }
            out.push_str(part);
            self.lines.push(out);
        }
    }

    fn blank(&mut self) {
        self.lines.push(String::new());
    }

    fn open(&mut self, text: &str) {
        self.line(text);
        self.indent += 1;
    }

    fn close(&mut self, text: &str) {
        self.indent = self.indent.saturating_sub(1);
        self.line(text);
    }

    fn fresh(&mut self) -> String {
        self.nodes += 1;
        format!("n{}", self.nodes)
    }

    fn warn(&mut self, code: &str, title: &str, span: plain_core::Span, note: &str) {
        self.diagnostics.push(
            Diagnostic::warning(code, title, self.file)
                .with_label(span, "")
                .with_note(note.to_string()),
        );
    }

    /// One component: a function that takes props and returns nodes.
    fn component(&mut self, component: &Component) {
        self.open(&format!(
            "function {}(props) {{",
            expr::js_ident(&component.name)
        ));
        let mut scope = Scope::new();
        for prop in &component.props {
            self.prop(prop, &scope);
            scope.bind(&prop.name, Binding::Accessor);
        }
        self.declare(&component.body, &mut scope);
        let root = self.render(&component.body, &mut scope);
        self.line(&format!("return {root};"));
        self.close("}");
    }

    fn prop(&mut self, prop: &PropDecl, scope: &Scope) {
        let name = expr::js_ident(&prop.name);
        let default = match &prop.default {
            Some(value) => format!("() => {}", expr::to_js(value, scope)),
            None => "undefined".to_string(),
        };
        self.line(&format!(
            "const {name} = P.prop(props, {}, {default});",
            expr::js_string(&prop.name)
        ));
    }

    /// Binds the names a block declares before any of it is emitted, so a handler
    /// written above the `let` it uses still compiles.
    fn declare(&self, nodes: &[Node], scope: &mut Scope) {
        for node in nodes {
            match node {
                Node::Let(declaration) => scope.bind(&declaration.name, Binding::Accessor),
                Node::Derive(declaration) => scope.bind(&declaration.name, Binding::Accessor),
                Node::Fn(function) => scope.bind(&function.name, Binding::Function),
                _ => {}
            }
        }
    }

    /// Emits a body and returns the expression that renders it.
    fn render(&mut self, nodes: &[Node], scope: &mut Scope) -> String {
        // One element is the root. Anything else needs a wrapper, and
        // `display: contents` keeps that wrapper out of the layout.
        if let [only] = nodes {
            match only {
                Node::Element(element) => return self.element(element, scope),
                Node::Use(invocation) => return self.invocation(invocation, scope),
                _ => {}
            }
        }
        let wrapper = self.fresh();
        self.line(&format!("const {wrapper} = P.el('div', 'pl-root');"));
        self.children(Some(&wrapper), nodes, scope);
        wrapper
    }

    /// Emits a list of nodes. Returns the variables holding the nodes it created,
    /// in order.
    fn children(&mut self, parent: Option<&str>, nodes: &[Node], scope: &mut Scope) -> Vec<String> {
        let mut created = Vec::new();
        for node in nodes {
            match node {
                Node::Element(element) => {
                    let var = self.element(element, scope);
                    self.append(parent, &var);
                    created.push(var);
                }
                Node::Use(invocation) => {
                    let var = self.invocation(invocation, scope);
                    self.append(parent, &var);
                    created.push(var);
                }
                Node::Let(declaration) => self.let_declaration(declaration, scope),
                Node::Derive(declaration) => self.derive_declaration(declaration, scope),
                Node::Fn(function) => self.function_declaration(function, scope),
                Node::Assign(assignment) => self.assignment(assignment, scope),
                Node::Return(returned) => self.return_statement(returned, scope),
                Node::Expr(value) => self.line(&format!("{};", expr::to_js(value, scope))),
                Node::If(condition) if condition.ui => self.condition(parent, condition, scope),
                Node::If(condition) => self.statement_if(condition, scope),
                Node::Each(each) if each.ui => self.each(parent, each, scope),
                Node::Each(each) => self.statement_each(each, scope),
                Node::Slot(slot) => {
                    if let Some(value) = self.slot(parent, slot) {
                        created.push(value);
                    }
                }
                // A deferred construct is already an error; emitting nothing keeps
                // the rest of the module buildable.
                Node::Deferred(_) => {}
            }
        }
        created
    }

    fn append(&mut self, parent: Option<&str>, var: &str) {
        if let Some(target) = parent {
            self.line(&format!("P.append({target}, {var});"));
        }
    }

    /// One element: create it, decorate it, then fill it.
    fn element(&mut self, element: &Element, scope: &mut Scope) -> String {
        let var = self.fresh();
        let tag = tag(element);
        let classes = classes(element);
        self.line(&format!(
            "const {var} = P.el({}, {});",
            expr::js_string(&tag),
            expr::js_string(&classes)
        ));

        for (name, value) in implied(&element.name) {
            self.line(&format!(
                "P.setAttr({var}, {name}, {value});",
                name = expr::js_string(name),
                value = expr::js_string(value)
            ));
        }
        if element.def.tag == "main" && !self.main_id && !has_attribute(element, "id") {
            self.main_id = true;
            self.line(&format!(
                "P.setAttr({var}, \"id\", {});",
                expr::js_string(crate::MAIN_ID)
            ));
        }

        self.content(&var, element, scope);
        for attribute in &element.attrs {
            self.attribute(&var, &element.name, attribute, scope);
        }
        for modifier in &element.modifiers {
            self.modifier(&var, &modifier.name, scope);
        }
        for prop in &element.props {
            self.style(&var, prop, scope);
        }
        if let Some(target) = &element.bind {
            self.bind(&var, &element.name, target, scope);
        }
        if let Some(condition) = &element.show {
            self.show(&var, condition, scope);
        }
        if element.name == "toggle" {
            self.toggle(&var, element, scope);
        }
        for handler in &element.handlers {
            self.handler(&var, handler, scope);
        }
        self.children(Some(&var), &element.children, scope);
        var
    }

    /// A component invocation: build the props and the children here, then call
    /// it. Anything styled or handled goes on a wrapper, because the component
    /// owns its own root.
    fn invocation(&mut self, invocation: &Use, scope: &mut Scope) -> String {
        // Anything the invocation carries but the component does not own — a
        // class, an attribute, a handler, `show` — needs a box to live on.
        let needs_wrapper = invocation.class.is_some()
            || !invocation.attrs.is_empty()
            || !invocation.handlers.is_empty()
            || !invocation.modifiers.is_empty()
            || !invocation.props_style.is_empty()
            || invocation.show.is_some();

        let call = format!(
            "{}({})",
            expr::js_ident(&invocation.name),
            self.prop_object(invocation, scope)
        );

        if !needs_wrapper {
            let var = self.fresh();
            self.line(&format!("const {var} = {call};"));
            return var;
        }

        let wrapper = self.fresh();
        let classes = use_classes(invocation);
        self.line(&format!(
            "const {wrapper} = P.el('div', {});",
            expr::js_string(&classes)
        ));
        let inner_var = self.fresh();
        self.line(&format!("const {inner_var} = {call};"));
        self.line(&format!("P.append({wrapper}, {inner_var});"));
        for attribute in &invocation.attrs {
            self.attribute(&wrapper, &invocation.name, attribute, scope);
        }
        for modifier in &invocation.modifiers {
            self.modifier(&wrapper, &modifier.name, scope);
        }
        for prop in &invocation.props_style {
            self.style(&wrapper, prop, scope);
        }
        if let Some(condition) = &invocation.show {
            self.show(&wrapper, condition, scope);
        }
        for handler in &invocation.handlers {
            self.handler(&wrapper, handler, scope);
        }
        wrapper
    }

    /// The props object a component is called with: accessors for values, and
    /// the children and slots built here in the caller's scope.
    fn prop_object(&mut self, invocation: &Use, scope: &mut Scope) -> String {
        let mut entries: Vec<String> = Vec::new();

        // A positional argument fills the declared props in order, so it has to
        // arrive under the name the component reads.
        let declared = self
            .components
            .get(&invocation.name)
            .cloned()
            .unwrap_or_default();
        for (index, value) in invocation.positional.iter().enumerate() {
            let name = declared
                .get(index)
                .cloned()
                .unwrap_or_else(|| format!("arg{index}"));
            entries.push(format!(
                "{}: {}",
                js_key(&name),
                expr::accessor(value, scope)
            ));
        }
        for (_, name, value) in &invocation.props {
            entries.push(format!(
                "{}: {}",
                js_key(name),
                expr::accessor(value, scope)
            ));
        }

        if !invocation.children.is_empty() {
            let value = self.detached(&invocation.children, scope);
            entries.push(format!("children: {value}"));
        }
        // Slots are keyed by name and go under `slots`, where a prop of the same
        // name cannot collide with them.
        if !invocation.slots.is_empty() {
            let mut slots: Vec<String> = Vec::new();
            for (name, nodes) in &invocation.slots {
                let value = self.detached(nodes, scope);
                slots.push(format!("{}: {value}", js_key(name)));
            }
            entries.push(format!("slots: {{ {} }}", slots.join(", ")));
        }

        if entries.is_empty() {
            "{}".to_string()
        } else {
            format!("{{ {} }}", entries.join(", "))
        }
    }

    fn content(&mut self, var: &str, element: &Element, scope: &Scope) {
        if element.args.is_empty() {
            return;
        }
        match element.def.role {
            // `image "/cat.png" "A cat sleeping"`: the first argument is what
            // the element loads or goes to, and the second is the words a person
            // (or a screen reader) gets instead.
            ArgRole::Src => {
                self.value_attribute(var, "src", &element.args[..1], scope);
                if element.args.len() > 1 && element.name == "image" {
                    self.value_attribute(var, "alt", &element.args[1..], scope);
                }
            }
            ArgRole::Href => {
                self.value_attribute(var, "href", &element.args[..1], scope);
                if element.args.len() > 1 {
                    self.text_of(var, &element.args[1..], scope);
                }
            }
            // The checker reports an argument an element has no use for.
            ArgRole::None => {}
            ArgRole::Content => self.text_of(var, &element.args, scope),
        }
    }

    /// Writes a list of values as the text of a node.
    fn text_of(&mut self, var: &str, values: &[Expr], scope: &Scope) {
        if let [only] = values {
            self.line(&format!(
                "P.setText({var}, {});",
                expr::accessor(only, scope)
            ));
            return;
        }
        let parts = values
            .iter()
            .map(|value| attribute_part(value, scope))
            .collect::<Vec<_>>()
            .join(", ");
        self.line(&format!(
            "P.setText({var}, () => [{parts}].map(P.text).join(' '));"
        ));
    }

    fn attribute(&mut self, var: &str, element: &str, attribute: &AttrProp, scope: &Scope) {
        if attribute.name == "class" {
            // A class attribute joins the generated ones rather than replacing
            // them, or the element would lose its styling.
            let base = classes_for_element(element, None);
            match attribute.values.as_slice() {
                [one] if !expr::is_dynamic(one, scope) => {
                    let extra = css_text(one, scope);
                    self.line(&format!(
                        "P.setClass({var}, {});",
                        expr::js_string(&join_classes(&base, &extra))
                    ));
                }
                _ => {
                    let value = self.attr_value(attribute, scope);
                    self.line(&format!(
                        "P.setClass({var}, {}, {value});",
                        expr::js_string(&base)
                    ));
                }
            }
            return;
        }
        let name = html_attribute(&attribute.name);
        self.value_attribute(var, &name, &attribute.values, scope);
    }

    /// The JavaScript for an attribute's value list.
    ///
    /// A bare word is the word itself — `type email`, `target _blank`, `rel
    /// noopener` — because that is what an HTML attribute value almost always
    /// is. A path, a call or an interpolation is a value to be worked out, and
    /// an empty list is a boolean attribute.
    fn attr_value(&self, attribute: &AttrProp, scope: &Scope) -> String {
        match attribute.values.as_slice() {
            [] => "true".to_string(),
            [one] => match one {
                // A bare word an attribute takes as a keyword, unless something
                // declares it, in which case it is that value.
                Expr::Name(word, _) if scope.binding(word).is_none() => expr::js_string(word),
                other => expr::accessor(other, scope),
            },
            many => {
                let parts = many
                    .iter()
                    .map(|value| attribute_part(value, scope))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("() => [{parts}].map(P.text).join(' ')")
            }
        }
    }

    fn value_attribute(&mut self, var: &str, name: &str, values: &[Expr], scope: &Scope) {
        let attribute = AttrProp {
            span: values.first().map(|v| v.span()).unwrap_or_default(),
            name: name.to_string(),
            values: values.to_vec(),
            dynamic: false,
        };
        let value = self.attr_value(&attribute, scope);
        self.line(&format!(
            "P.setAttr({var}, {}, {value});",
            expr::js_string(name)
        ));
    }

    fn modifier(&mut self, var: &str, name: &str, _scope: &Scope) {
        if css::is_style_modifier(name) {
            // Already in the generated class.
            return;
        }
        match name {
            // A decorative image is announced as nothing at all, which is the
            // only way to keep a screen reader from reading a file name aloud.
            "decorative" => {
                self.line(&format!("P.setAttr({var}, \"alt\", \"\");"));
                self.line(&format!("P.setAttr({var}, \"aria-hidden\", \"true\");"));
            }
            // `head` on a table cell makes it a header cell; the tag change
            // happens in `tag`, and the scope is what makes it usable.
            "head" => {
                self.line(&format!("P.setAttr({var}, \"scope\", \"col\");"));
            }
            "optional" => {
                self.line(&format!("P.setAttr({var}, \"aria-required\", \"false\");"));
            }
            other => {
                self.line(&format!(
                    "P.setAttr({var}, {}, true);",
                    expr::js_string(&html_attribute(other))
                ));
            }
        }
    }

    /// A style property the stylesheet could not decide, written as an inline
    /// style effect instead.
    fn style(&mut self, var: &str, prop: &StyleProp, scope: &Scope) {
        if !css::is_dynamic(prop) {
            return;
        }
        self.line(&format!(
            "P.setStyle({var}, {}, {});",
            expr::js_string(&css::css_name(&prop.name)),
            expr_or_template(prop, scope)
        ));
    }

    fn bind(&mut self, var: &str, element: &str, target: &crate::ast::BindTarget, scope: &Scope) {
        let (root, keys) = expr::assignment(&target.path, scope);
        let get = if keys.is_empty() {
            format!("() => {root}()")
        } else {
            format!("() => {}", path_read(&root, &keys))
        };
        let set = if keys.is_empty() {
            // A slider and a number input hand back a string; the value they
            // represent is a number.
            if element == "slider" {
                format!("(value) => {root}.set(Number(value))")
            } else {
                format!("(value) => {root}.set(value)")
            }
        } else if element == "slider" {
            format!(
                "(value) => P.assign({root}, [{}], Number(value))",
                keys.join(", ")
            )
        } else {
            format!("(value) => P.assign({root}, [{}], value)", keys.join(", "))
        };
        let kind = if matches!(element, "check" | "radio") {
            "checked"
        } else {
            "value"
        };
        self.line(&format!(
            "P.bind({var}, {get}, {set}, {kind});",
            kind = expr::js_string(kind)
        ));
    }

    /// A `toggle` is a button that switches, so it needs `aria-checked` and a
    /// click that flips it: neither is behaviour the writer has to describe.
    fn toggle(&mut self, var: &str, element: &Element, scope: &Scope) {
        let Some(target) = &element.bind else {
            self.warn(
                "W130",
                "a `toggle` without `bind` has no state to switch",
                element.span,
                "Give it something to hold the value: `toggle bind dark`.",
            );
            return;
        };
        let (root, keys) = expr::assignment(&target.path, scope);
        let read = if keys.is_empty() {
            format!("{root}()")
        } else {
            path_read(&root, &keys)
        };
        let write = if keys.is_empty() {
            format!("{root}.set(!{root}())")
        } else {
            format!("P.assign({root}, [{}], !({read}))", keys.join(", "))
        };
        self.line(&format!(
            "P.setAttr({var}, \"aria-checked\", () => Boolean({read}));"
        ));
        self.line(&format!("P.on({var}, 'click', (event) => {{ {write}; }});"));
    }

    /// `show` hides without removing, so the element keeps its state and its
    /// place in the document.
    fn show(&mut self, var: &str, condition: &Expr, scope: &Scope) {
        self.line(&format!(
            "P.setStyle({var}, 'display', () => ({}) ? '' : 'none');",
            expr::to_js(condition, scope)
        ));
    }

    fn handler(&mut self, var: &str, handler: &Handler, scope: &mut Scope) {
        let mut options: Vec<String> = Vec::new();
        if handler.modifiers.contains(&"once".to_string()) {
            options.push("once: true".to_string());
        }
        if handler.modifiers.contains(&"capture".to_string()) {
            options.push("capture: true".to_string());
        }
        if handler.modifiers.contains(&"passive".to_string()) {
            options.push("passive: true".to_string());
        }
        let options_js = if options.is_empty() {
            "undefined".to_string()
        } else {
            format!("{{ {} }}", options.join(", "))
        };
        let filter = match key_filter(handler) {
            Some(test) => format!("(event) => {test}"),
            None => "undefined".to_string(),
        };

        let mut inner = scope.child();
        inner.bind("event", Binding::Value);
        self.declare(&handler.body, &mut inner);

        self.open(&format!(
            "P.on({var}, {}, (event) => {{",
            expr::js_string(&handler.event)
        ));
        if handler.modifiers.contains(&"prevent".to_string()) {
            self.line("event.preventDefault();");
        }
        if handler.modifiers.contains(&"stop".to_string()) {
            self.line("event.stopPropagation();");
        }
        if handler.modifiers.contains(&"self".to_string()) {
            self.line("if (event.target !== event.currentTarget) return;");
        }
        self.children(None, &handler.body, &mut inner);
        self.close(&format!("}}, {options_js}, {filter});"));
    }

    /// `if` in a statement position is a branch, and stays one.
    fn statement_if(&mut self, condition: &If, scope: &mut Scope) {
        let mut first = true;
        for (test, body) in &condition.branches {
            let keyword = if first { "if (" } else { "} else if (" };
            first = false;
            let mut inner = scope.child();
            self.declare(body, &mut inner);
            self.open(&format!("{keyword}{}) {{", expr::to_js(test, scope)));
            self.children(None, body, &mut inner);
            // The branch's own closing brace belongs to whatever follows it: the
            // next `else if`, the `else`, or the final brace below.
            self.indent = self.indent.saturating_sub(1);
        }
        if let Some(body) = &condition.else_branch {
            let mut inner = scope.child();
            self.declare(body, &mut inner);
            self.open("} else {");
            self.children(None, body, &mut inner);
            self.indent = self.indent.saturating_sub(1);
        }
        self.line("}");
    }

    /// `each` in a statement position is a loop over the values themselves.
    fn statement_each(&mut self, each: &Each, scope: &mut Scope) {
        let mut inner = scope.child();
        let head = match &each.index {
            Some(index) => format!(
                "for (const [{}, {}] of ({}).entries()) {{",
                expr::js_ident(index),
                expr::js_ident(&each.item),
                expr::to_js(&each.iter, scope)
            ),
            None => format!(
                "for (const {} of {}) {{",
                expr::js_ident(&each.item),
                expr::to_js(&each.iter, scope)
            ),
        };
        // Inside a statement loop the names hold plain values, not accessors:
        // there is nothing to react to until the loop assigns to real state.
        inner.bind(&each.item, Binding::Value);
        if let Some(index) = &each.index {
            inner.bind(index, Binding::Value);
        }
        self.declare(&each.body, &mut inner);
        self.open(&head);
        self.children(None, &each.body, &mut inner);
        self.close("}");
    }

    /// `if` in a UI position removes and rebuilds; `show` only hides.
    fn condition(&mut self, parent: Option<&str>, condition: &If, scope: &mut Scope) {
        let Some(target) = parent else {
            self.warn(
                "W131",
                "an `if` at the root of a component has nothing to attach to",
                condition.span,
                "Put it inside an element.",
            );
            return;
        };
        let mut branches = condition.branches.iter();
        let Some((first, nodes)) = branches.next() else {
            return;
        };

        let then_factory = self.factory(nodes, scope);
        let otherwise = match branches.next() {
            // Further `else if`s become an `if` inside the else branch. That is
            // what the source means, and `detached` gives the nested branch the
            // host it needs.
            Some(_) => {
                let rest = If {
                    span: condition.span,
                    ui: true,
                    branches: branches.cloned().collect(),
                    else_branch: condition.else_branch.clone(),
                };
                self.factory(&[Node::If(rest)], scope)
            }
            None => match &condition.else_branch {
                Some(nodes) => self.factory(nodes, scope),
                None => "null".to_string(),
            },
        };
        self.line(&format!(
            "P.when({target}, () => {}, {then_factory}, {otherwise});",
            expr::to_js(first, scope)
        ));
    }

    /// Emits a node list that has no parent of its own yet: a component's
    /// children or slots, an `if` branch, an `each` row. Returns the JavaScript
    /// expression that yields its nodes.
    ///
    /// Control flow inserts relative to a parent, so a list that starts with `if`
    /// or `each` gets a wrapper to insert into. `display: contents` keeps that
    /// wrapper out of the layout, which is the whole reason it is allowed to
    /// exist.
    fn detached(&mut self, nodes: &[Node], scope: &mut Scope) -> String {
        let host = if needs_host(nodes) {
            let var = self.fresh();
            self.line(&format!("const {var} = P.el('div', 'pl-fragment');"));
            Some(var)
        } else {
            None
        };
        self.declare(nodes, scope);
        let created = self.children(host.as_deref(), nodes, scope);
        match host {
            Some(var) => var,
            None => format!("[{}]", created.join(", ")),
        }
    }

    /// A branch of an `if`, or the body of an `each`: a function the runtime
    /// calls inside a scope of its own.
    fn factory(&mut self, nodes: &[Node], scope: &mut Scope) -> String {
        let before = self.lines.len();
        // The body is written flush left and indented once, as a unit, when the
        // factory is composed into the call that owns it.
        let outside = self.indent;
        self.indent = 0;
        let mut inner = scope.child();
        let value = self.detached(nodes, &mut inner);
        self.indent = outside;
        let body = self.lines.split_off(before);
        let indented = body
            .iter()
            .map(|line| format!("  {line}"))
            .collect::<Vec<_>>()
            .join("\n");
        format!("() => {{\n{indented}\n  return {value};\n}}")
    }

    fn each(&mut self, parent: Option<&str>, each: &Each, scope: &mut Scope) {
        let Some(target) = parent else {
            self.warn(
                "W132",
                "an `each` at the root of a component has nothing to attach to",
                each.span,
                "Put it inside an element.",
            );
            return;
        };

        let mut inner = scope.child();
        inner.bind(&each.item, Binding::Accessor);
        if let Some(index) = &each.index {
            inner.bind(index, Binding::Accessor);
        }
        self.declare(&each.body, &mut inner);
        let body = self.factory(&each.body, &mut inner);

        // The key is read from the raw item, not the row's accessor, which is
        // what lets the runtime match a row up after the list changes.
        let mut key_scope = scope.child();
        key_scope.bind(&each.item, Binding::Value);
        if let Some(index) = &each.index {
            key_scope.bind(index, Binding::Value);
        }
        let params = match &each.index {
            Some(index) => format!("{}, {}", expr::js_ident(&each.item), expr::js_ident(index)),
            None => format!("{}, index", expr::js_ident(&each.item)),
        };
        let key = match &each.key {
            Some(value) => format!("({params}) => {}", expr::to_js(value, &key_scope)),
            None => "undefined".to_string(),
        };

        self.line(&format!(
            "P.each({target}, () => {}, ({params}) => {}, {key});",
            expr::to_js(&each.iter, scope),
            body
        ));
    }

    /// A slot is a value the component was handed, so with no parent to append
    /// to it is simply returned, and `toNodes` flattens it into the surrounding
    /// list.
    fn slot(&mut self, parent: Option<&str>, slot: &Slot) -> Option<String> {
        let read = match &slot.name {
            Some(name) => format!("P.slot(props, {})", expr::js_string(name)),
            None => "P.slot(props)".to_string(),
        };
        match parent {
            Some(target) => {
                self.line(&format!("P.append({target}, {read});"));
                None
            }
            None => Some(read),
        }
    }

    fn let_declaration(&mut self, declaration: &Let, scope: &Scope) {
        let name = expr::js_ident(&declaration.name);
        let value = expr::to_js(&declaration.value, scope);
        match &declaration.persist {
            Some(persist) => {
                let key = match &persist.key {
                    Expr::Str(parts, _) => expr::js_string(&plain_text(parts)),
                    other => expr::to_js(other, scope),
                };
                let area = if persist.session { ", 'session'" } else { "" };
                self.line(&format!(
                    "const {name} = P.persisted({key}, {value}{area});"
                ));
            }
            None => self.line(&format!("const {name} = P.signal({value});")),
        }
    }

    fn derive_declaration(&mut self, declaration: &Derive, scope: &Scope) {
        let name = expr::js_ident(&declaration.name);
        self.line(&format!(
            "const {name} = P.computed(() => {});",
            expr::to_js(&declaration.value, scope)
        ));
    }

    fn function_declaration(&mut self, function: &FnDecl, scope: &Scope) {
        let name = expr::js_ident(&function.name);
        let params = function
            .params
            .iter()
            .map(|param| match &param.default {
                Some(value) => format!(
                    "{} = {}",
                    expr::js_ident(&param.name),
                    expr::to_js(value, scope)
                ),
                None => expr::js_ident(&param.name),
            })
            .collect::<Vec<_>>()
            .join(", ");

        let mut inner = scope.child();
        for param in &function.params {
            inner.bind(&param.name, Binding::Value);
        }
        self.declare(&function.body, &mut inner);

        self.open(&format!("function {name}({params}) {{"));
        self.children(None, &function.body, &mut inner);
        self.close("}");
    }

    fn assignment(&mut self, assignment: &Assign, scope: &Scope) {
        let (root, keys) = expr::assignment(&assignment.target, scope);
        let value = expr::to_js(&assignment.value, scope);
        if keys.is_empty() {
            self.line(&format!("{root}.set({value});"));
        } else {
            self.line(&format!(
                "P.assign({root}, [{}], {value});",
                keys.join(", ")
            ));
        }
    }

    fn return_statement(&mut self, returned: &Return, scope: &Scope) {
        match &returned.value {
            Some(value) => self.line(&format!("return {};", expr::to_js(value, scope))),
            None => self.line("return;"),
        }
    }
}

/// True when a detached node list needs a wrapper to insert into, because it
/// starts with control flow rather than with an element.
fn needs_host(nodes: &[Node]) -> bool {
    nodes.iter().any(|node| match node {
        Node::If(condition) => condition.ui,
        Node::Each(each) => each.ui,
        _ => false,
    })
}

/// The HTML tag an element becomes.
fn tag(element: &Element) -> String {
    // `heading level 2` is an <h2>, and `table-cell head` is a <th>: both are
    // decided by something the writer wrote on the element, not by a style.
    if element.def.tag == "h1" {
        if let Some(level) = static_attribute(element, "level") {
            let digits: String = level.chars().filter(|c| c.is_ascii_digit()).collect();
            if (1..=6).contains(&digits.parse::<u32>().unwrap_or(1)) {
                return format!("h{digits}");
            }
        }
    }
    if element.def.tag == "td" && has_modifier(element, "head") {
        return "th".to_string();
    }
    element.def.tag.to_string()
}

/// The classes an element carries: its layout primitive and its generated one.
fn classes(element: &Element) -> String {
    let base = classes_for_element(&element.name, element.class.as_deref());
    match static_attribute(element, "class") {
        Some(extra) => join_classes(&base, &extra),
        None => base,
    }
}

fn classes_for_element(name: &str, generated: Option<&str>) -> String {
    let mut out: Vec<String> = Vec::new();
    let layout = tables::element(name).map(|def| def.layout);
    match layout {
        Some(Layout::Stack) => out.push("pl-stack".to_string()),
        Some(Layout::Row) => out.push("pl-row".to_string()),
        Some(Layout::Grid) => out.push("pl-grid".to_string()),
        Some(Layout::Layer) => out.push("pl-layer".to_string()),
        _ => {}
    }
    if name == "spacer" {
        out.push("pl-spacer".to_string());
    }
    if let Some(class) = generated {
        out.push(class.to_string());
    }
    out.join(" ")
}

fn use_classes(invocation: &Use) -> String {
    let mut out = match invocation.class.as_deref() {
        Some(class) => class.to_string(),
        None => String::new(),
    };
    // A styled component invocation is a box that stacks, so the props it was
    // given have something to apply to.
    if !out.is_empty() {
        out.insert_str(0, "pl-stack ");
    } else {
        out = "pl-stack".to_string();
    }
    out
}

fn join_classes(base: &str, extra: &str) -> String {
    let mut parts: Vec<&str> = base.split_whitespace().collect();
    for class in extra.split_whitespace() {
        if !parts.contains(&class) {
            parts.push(class);
        }
    }
    parts.join(" ")
}

/// Attributes Plain's vocabulary implies, so the writer does not have to spell
/// out what they already said by choosing the element.
fn implied(name: &str) -> Vec<(&'static str, &'static str)> {
    match name {
        "input" => vec![("type", "text")],
        "check" => vec![("type", "checkbox")],
        "radio" => vec![("type", "radio")],
        "slider" => vec![("type", "range")],
        "toggle" => vec![("type", "button"), ("role", "switch")],
        "modal" => vec![("role", "dialog"), ("aria-modal", "true")],
        "skeleton" => vec![("aria-hidden", "true")],
        "divider" => vec![("role", "separator")],
        _ => vec![],
    }
}

/// Plain attribute names that are not HTML attribute names.
fn html_attribute(name: &str) -> String {
    match name {
        // A control has no caption of its own, so its name goes on the control.
        "label" => "aria-label".to_string(),
        // ARIA 1.2, and not every screen reader announces it yet; the checker
        // says so rather than letting it pass silently.
        "describe" => "aria-description".to_string(),
        "live" => "aria-live".to_string(),
        "test" => "data-testid".to_string(),
        "to" => "href".to_string(),
        other => other.to_string(),
    }
}

fn has_attribute(element: &Element, name: &str) -> bool {
    element.attrs.iter().any(|attribute| attribute.name == name)
}

fn has_modifier(element: &Element, name: &str) -> bool {
    element.modifiers.iter().any(|m| m.name == name)
}

/// The value of an attribute that is a compile-time constant.
fn static_attribute(element: &Element, name: &str) -> Option<String> {
    let attribute = element.attrs.iter().find(|a| a.name == name)?;
    if attribute.dynamic {
        return None;
    }
    Some(
        attribute
            .values
            .iter()
            .map(|value| css_text(value, &Scope::new()))
            .collect::<Vec<_>>()
            .join(" "),
    )
}

/// The text of a value used where CSS or HTML text is wanted rather than
/// JavaScript.
fn css_text(value: &Expr, scope: &Scope) -> String {
    match value {
        Expr::Str(parts, _) => plain_text(parts),
        Expr::Length(number, unit, _) => format!("{}{unit}", crate::parser::trim_number(*number)),
        Expr::Color(text, _) => text.clone(),
        Expr::Int(number, _) => number.to_string(),
        Expr::Float(number, _) => crate::parser::trim_number(*number),
        Expr::Name(name, _) => name.clone(),
        Expr::Bool(flag, _) => flag.to_string(),
        Expr::None(_) => String::new(),
        other => expr::to_js(other, scope),
    }
}

/// The literal text of a string, ignoring interpolations.
fn plain_text(parts: &[crate::ast::StrPart]) -> String {
    parts
        .iter()
        .map(|part| match part {
            crate::ast::StrPart::Text(text) => text.as_str(),
            crate::ast::StrPart::Expr(_) => "",
        })
        .collect()
}

/// One item of a multi-value attribute, as JavaScript.
fn attribute_part(value: &Expr, scope: &Scope) -> String {
    match value {
        Expr::Name(word, _) if scope.binding(word).is_none() => expr::js_string(word),
        other => expr::to_js(other, scope),
    }
}

/// An object key, quoted when JavaScript would not take it bare.
fn js_key(name: &str) -> String {
    let bare = name
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
        && !name.starts_with(|c: char| c.is_ascii_digit());
    if bare {
        name.to_string()
    } else {
        expr::js_string(name)
    }
}

/// Reads a path out of a signal's value: `user().address.city`.
fn path_read(root: &str, keys: &[String]) -> String {
    let mut out = format!("{root}()");
    for key in keys {
        if key.starts_with('"') {
            // A quoted key is a field name; anything else is an index expression.
            let field = key.trim_matches('"');
            out = if is_bare_ident(field) {
                format!("{out}.{field}")
            } else {
                format!("{out}[{key}]")
            };
        } else {
            out = format!("{out}[{key}]");
        }
    }
    out
}

fn is_bare_ident(name: &str) -> bool {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) if first.is_ascii_alphabetic() || first == '_' || first == '$' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

/// The test a key filter compiles to, if the handler has one.
fn key_filter(handler: &Handler) -> Option<String> {
    let mut tests: Vec<String> = Vec::new();
    for key in &handler.keys {
        let value = tables::KEY_FILTERS
            .iter()
            .find(|(plain, _)| *plain == key.as_str())
            .map(|(_, dom)| *dom)
            .unwrap_or(key.as_str());
        tests.push(format!("event.key === {}", expr::js_string(value)));
    }
    for modifier in &handler.key_mods {
        let property = match modifier.as_str() {
            "ctrl" => "ctrlKey",
            "shift" => "shiftKey",
            "alt" => "altKey",
            "meta" => "metaKey",
            other => other,
        };
        tests.push(format!("event.{property}"));
    }
    if tests.is_empty() {
        None
    } else {
        Some(tests.join(" && "))
    }
}

/// A style value the runtime has to work out, as one JavaScript expression.
fn expr_or_template(prop: &StyleProp, scope: &Scope) -> String {
    let value = css::value_js(prop, scope);
    format!("() => {value}")
}

