//! The Plain JavaScript runtime.
//!
//! The runtime lives as a real, editable file in `runtime/plain.runtime.js` and
//! is embedded into the compiler binary at build time, so a Plain build needs
//! nothing installed and nothing downloaded. It is tested separately, against a
//! real DOM, by `runtime/test/runtime.test.js`.

/// The runtime source, emitted verbatim as `plain.runtime.js`.
pub const RUNTIME: &str = include_str!("../../../runtime/plain.runtime.js");

/// The file name the runtime is written to.
pub const RUNTIME_FILE: &str = "plain.runtime.js";

